"""Runs every queries/*.sql file in order against sec.duckdb.

Each file may contain several statements; the result of the last one is saved to results/<name>.csv and
appended, as a markdown table, to results/RESULTS.md.

Usage: python run_queries.py [--only 03]
"""
import argparse
from pathlib import Path

import duckdb

HERE = Path(__file__).parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(HERE / "sec.duckdb"))
    ap.add_argument("--only", help="run only files whose name starts with this prefix")
    a = ap.parse_args()
    con = duckdb.connect(a.db)
    out = HERE / "results"
    out.mkdir(exist_ok=True)
    md = []
    for f in sorted((HERE / "queries").glob("*.sql")):
        if a.only and not f.name.startswith(a.only):
            continue
        sql = f.read_text(encoding="utf-8")
        statements = [s for s in sql.split(";") if s.strip() and not all(
            line.strip().startswith("--") or not line.strip() for line in s.splitlines())]
        for s in statements[:-1]:
            con.execute(s)
        df = con.execute(statements[-1]).df()
        df.to_csv(out / f"{f.stem}.csv", index=False)
        title = next((l[2:].strip() for l in sql.splitlines() if l.startswith("--")), f.stem)
        md.append(f"## {title}\n\n{df.to_markdown(index=False, floatfmt='.3g')}\n")
        print(f"{f.name}: {len(df)} rows")
        print(df.head(20).to_string(index=False))
        print()
    if not a.only:
        (out / "RESULTS.md").write_text("# Query results\n\nGenerated by `run_queries.py`.\n\n" + "\n".join(md),
                                        encoding="utf-8")


if __name__ == "__main__":
    main()
